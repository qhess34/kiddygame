// RÈGLES DE SEGMENTATION ET DE COULEUR RETENUES
// (rouge = voyelle, bleu = consonne, vert = graphème de 2 lettres ou plus, noir = lettre muette)
//
// 1. Une lettre = un son → voyelle (rouge) ou consonne (bleu). Les voyelles accentuées
//    é, è, ê, â, ô, î, ï sont des graphèmes distincts de leur lettre de base.
//    Le « e » prononcé [ə] (cheval, petit) ou [ɛ] devant deux consonnes / une consonne
//    prononcée (serpent, escargot, lunettes, miel) reste la voyelle « e » (rouge).
// 2. Plusieurs lettres = un seul son → graphème complexe vert, indivisible :
//    ch, ou, on, an, en, am, om, in, ain, ei, ai, eu, œu, oi, au, eau, gn, ph, qu, gu, gh,
//    ien (chien), aon (paon), er/ez/et finaux prononcés [e]/[ɛ] (panier, nez, poulet, robinet),
//    ill (fille, papillon), eil / eill / euil / euill / ouill (soleil, abeille, écureuil…).
// 3. CONSONNES DOUBLÉES : quand deux lettres identiques codent UN seul son, elles forment un
//    digramme vert : ss, ll, tt, mm, nn, rr, pp, gg, zz, cc (accordéon).
//    Quand elles codent deux sons différents, elles restent deux consonnes bleues
//    (coccinelle : c[k] + c[s]).
//    Les syllabes écrites coupent ENTRE les deux lettres, selon la convention scolaire
//    (bal-lon, pois-son, pom-me, ca-rot-te) : le moteur l'accepte, la couleur suit la lettre.
// 4. LETTRES MUETTES (noir, suffixe « _ ») : e final (e_), t, s, d, p, h, f finaux ou
//    internes non prononcés (chat, souris, renard, loup, hibou, cerf, rhinocéros).
//    « est » = e + s_ + t_.
// 5. Le « e » final muet forme une syllabe écrite (lu-ne, to-ma-te) ; sa prononciation
//    est fournie dans `ssay` sous une forme lisible par la synthèse (« neu », « teu »…).
// 6. Syllabes : syllabes écrites conventionnelles (to-ma-te, cho-co-lat, pa-pi-llon,
//    pi-a-no, li-on). Les mots en -ille d'une seule syllabe orale restent d'un bloc (fille).
// 7. y : consonne [j] dans yoyo / kayak / yoga / yeux (« y:c »), voyelle [i] dans cygne / stylo / myrtille.
// 8. « ill » après une voyelle reste le graphème ill (médaille, cuillère, billet, coquillage) ;
//    syllabes écrites coupées comme a-beil-le : mé-dail-le, cuil-lè-re, bil-let.
// 9. Muettes rares (niveau 5+) : z final (riz), x final (ciseaux, yeux, deux), i de oignon (o i_ gn on).
//    Graphèmes rares du niveau 7 : sh (sushi), q final (coq, cinq), ail (corail), aî (chaîne),
//    ay [ɛj] (crayon), im (imprimante), û (flûte). x se lit [s] dans six et dix (niveau 7).
// 10. Nombres : emoji touches 2️⃣…🔟 ; « un » reste un mot-outil (SMALL_WORDS).
//
// PROGRESSION : niveau 1 = CV simples sans digramme, sans lettre muette et sans groupe de
// consonnes en attaque (les mots comme ski, métro, blé, clé vont au niveau 2) ; niveau 2 = e muet,
